-- Postgre Sql
-- Postgre Sql adalah DBMS Relational OpenSource yang sangat populer, tertuatama di perusahaan enterprise
-- Tidak Hanya open source, Postgre Sql juga gratis untuk digunakan
-- Proyek PostgreSQL dimulai sejak tahun 1986, dibawah arahan professor Michael Stonebreaker di Universitas California, Berkeley
-- https://www.postgresql.org/

-- PostreSQL vs MySQL
-- Mysql sampai sekarang menjadi salah sat DBMS yang paling populer di dunia
-- Namun, banyak perushaan besar yang menggunakan PostgreSQL, hal ini dikarenakan PostgreSQL, memiliki fitur yang lebih kaya dibandingkan MySQL
-- MySQL fokus pada performa dan kecepatan, oleh karena itu fitur nya tak sebnyak di PostgresSQL