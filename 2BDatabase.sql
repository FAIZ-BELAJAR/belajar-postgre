-- Database adalah tempat kita menyimpan table di PostgreSql
-- Jika kita misalkan table d PostgreSQL, adalah sebuah File, maka database adalah foldernya, dimana kita bisa menyimpan banyak table di sebuah database
-- Biasanya pembuatan kita akan membuat satu database untuk satu jenis aplikasi, walaupun satu aplikasi bisa menggunakan lebih dari satu database, namun lumrahnya, satu apalikasi akan menggunakan satu database

-- Membuat Database
-- Untuk membuat database baru kita perlu menggunakan command:
-- create database nama_database;
create database databas_baru;


-- Menghapus Database
-- Untuk menghapus database kita perlu menggunakan command:
-- drop database nama_database;
drop database databas_baru;